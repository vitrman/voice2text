"""Слова-паразиты: убираются только звуки-заполнители, настоящие слова остаются."""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from postprocess import drop_fillers  # noqa: E402


def check(source: str, expected: str) -> bool:
    got = drop_fillers(source)
    ok = got == expected
    print(f"{'ok  ' if ok else 'FAIL'} {source!r} -> {got!r}")
    if not ok:
        print(f"     ожидалось {expected!r}")
    return ok


def main() -> int:
    cases = [
        # звуки-заполнители в разных написаниях
        ("Э-э-э, ну я не знаю.", "Ну я не знаю."),
        ("а-а-а, понял", "Понял"),
        ("Ээээ, да.", "Да."),
        ("ммм, интересно", "Интересно"),
        ("н-н-н, не помню", "Не помню"),
        ("э э э, подожди", "Подожди"),
        ("да-да-да, конечно", "да, конечно"),
        # растянутое окончание настоящего слова сжимается, а не удаляется
        ("ну-у, не знаю", "ну, не знаю"),
        ("да-а, согласен", "да, согласен"),
        # настоящие слова паразиты остаются: их нельзя резать по списку
        ("Типа данных не хватает.", "Типа данных не хватает."),
        ("Значит результат верный.", "Значит результат верный."),
        ("Ну, попробуем ещё.", "Ну, попробуем ещё."),
        ("Короче путь через двор.", "Короче путь через двор."),
        # обычный текст и аббревиатуры не трогаем
        ("Привет, как дела?", "Привет, как дела?"),
        ("ООО «Ромашка» закрылось.", "ООО «Ромашка» закрылось."),
        ("Мне нужен адрес офиса.", "Мне нужен адрес офиса."),
        ("Это это не повтор.", "Это это не повтор."),
        # заполнитель в начале и в середине
        ("Я, э-э-э, забыл.", "Я, забыл."),
        ("Пришёл, э-э-э, и ушёл.", "Пришёл, и ушёл."),
        # связка: в начале фразы и после точки, с лишними запятыми
        ("Э-э-э, а-а-а, ну я не знаю. Ммм, типа данных нет.",
         "Ну я не знаю. Типа данных нет."),
        ("Привет. Э-э-э, как дела?", "Привет. Как дела?"),
    ]
    results = [check(source, expected) for source, expected in cases]

    logged: list[str] = []
    drop_fillers("Э-э-э, а-а-а, да.", log=logged.append)
    log_ok = bool(logged) and "заполнителей" in logged[0]
    print(f"{'ok  ' if log_ok else 'FAIL'} журнал: {logged}")
    results.append(log_ok)

    # на чистом тексте фильтр не должен ничего менять
    clean = "Сегодня встреча в 15:00, обсудим бюджет и сроки."
    untouched = drop_fillers(clean) == clean
    print(f"{'ok  ' if untouched else 'FAIL'} чистый текст не меняется")
    results.append(untouched)

    ok = all(results)
    print("результат:", "ok" if ok else "ОШИБКА")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
